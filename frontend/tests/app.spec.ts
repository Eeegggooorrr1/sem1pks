test('bulk action, filtered CSV export and checked CSV import', async ({ page }) => {
  const code = unique()
  await login(page)
  await createListing(page, code)
  await page.getByRole('link', { name: 'Каталог', exact: true }).click()
  await page.getByLabel('Поиск', { exact: true }).fill(code)
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(page.getByRole('link', { name: `Книга ${code}` })).toBeVisible()
  await page.getByLabel(`Выбрать ${code}`, { exact: true }).check()
  await page.getByLabel('Массовая операция').selectOption('ADD_TAG')
  await page.getByLabel('Тег', { exact: true }).filter({ visible: true }).fill('массовый')
  await page.getByRole('button', { name: 'Применить', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Применить', exact: true }).click()
  await expect(page.getByText('Успешно: 1. Ошибок: 0.')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать CSV', exact: true }).click()
  const exported = await download
  expect(exported.suggestedFilename()).toBe('listings.csv')
  await page.getByRole('link', { name: 'Импорт CSV', exact: true }).click()
  const mode = page.getByRole('combobox', { name: 'Режим', exact: true })
  await mode.selectOption('UPSERT')
  await page.getByLabel('Файл CSV').setInputFiles({
    name: exported.suggestedFilename(), mimeType: 'text/csv', buffer: await readFile(await exported.path()),
  })
  await page.getByRole('button', { name: 'Проверить файл', exact: true }).click()
  await expect(page.getByText('Корректных записей: 1. С ошибками: 0.')).toBeVisible()
  await page.getByRole('button', { name: 'Применить импорт', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Применить импорт', exact: true }).click()
  await expect(page.getByText('Создано: 0. Обновлено: 1.')).toBeVisible()

  await mode.selectOption('NEW_ONLY')
  const importedCode = unique()
  await page.getByLabel('Файл CSV').setInputFiles({ name: 'input.csv', mimeType: 'text/csv', buffer: Buffer.from(`code,title,description,price,status,categoryCode,featured,tags\r\n${importedCode},Импорт,Описание,100,ACTIVE,BOOKS,false,тест\r\n`) })
  await page.getByRole('button', { name: 'Проверить файл', exact: true }).click()
  await expect(page.getByText('Корректных записей: 1. С ошибками: 0.')).toBeVisible()
  await page.getByRole('button', { name: 'Применить импорт', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Применить импорт', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Импорт завершен' })).toBeVisible()
})

