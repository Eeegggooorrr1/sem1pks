test('buyer places and completes an order, seller confirms and closes the listing', async ({ page, browser }) => {
  const password = process.env.E2E_DEMO_PASSWORD!
  const sellerContext = await browser.newContext()
  try {
    const seller = await sellerContext.newPage()
    await login(seller, 'demo2@example.com', password)
    const code = unique()
    await createListing(seller, code)
    const listingUrl = seller.url()
    await expect(seller.getByRole('button', { name: 'В архив', exact: true })).toHaveCount(0)
    await login(page, 'demo1@example.com', password)
    await page.goto(listingUrl)
    await page.getByRole('button', { name: 'Оформить заказ', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Оформить заказ', exact: true }).click()
    const outgoing = page.getByRole('row').filter({ hasText: code })
    await expect(outgoing).toContainText('Ожидает подтверждения')
    await seller.getByRole('link', { name: 'Продажи', exact: true }).click()
    const incoming = seller.getByRole('row').filter({ hasText: code })
    await incoming.getByRole('button', { name: 'Подтвердить', exact: true }).click()
    await expect(incoming).toContainText('Подтвержден')
    await page.getByRole('button', { name: 'Обновить', exact: true }).click()
    await outgoing.getByRole('button', { name: 'Завершить покупку', exact: true }).click()
    await expect(outgoing).toContainText('Завершен')
    await page.screenshot({ path: 'test-results/orders.png', fullPage: true })
    await seller.goto(listingUrl)
    await seller.getByRole('button', { name: 'Закрыть объявление', exact: true }).click()
    await seller.getByRole('dialog').getByRole('button', { name: 'Закрыть объявление', exact: true }).click()
    await expect(seller.getByText('Закрыто', { exact: true })).toBeVisible()
    await page.goto(listingUrl)
    await expect(page.getByText('Закрыто', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Оформить заказ', exact: true })).toHaveCount(0)
  } finally {
    await sellerContext.close()
  }
})
