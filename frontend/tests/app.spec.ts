import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const adminEmail = process.env.E2E_ADMIN_EMAIL!, adminPassword = process.env.E2E_ADMIN_PASSWORD!
if (!adminEmail || !adminPassword || !process.env.E2E_DEMO_PASSWORD) throw new Error('Укажите тестовые учетные записи E2E_ADMIN_EMAIL, E2E_ADMIN_PASSWORD, E2E_DEMO_PASSWORD')
const unique = () => `TEST-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`
async function login(page: Page, email = adminEmail, password = adminPassword) {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Объявления', exact: true })).toBeVisible()
}
async function createListing(page: Page, code: string) {
  await page.getByRole('link', { name: 'Создать объявление' }).click()
  await page.getByLabel('Код', { exact: true }).fill(code)
  await page.getByRole('combobox', { name: 'Категория', exact: true }).selectOption({ label: 'Книги' })
  await page.getByLabel('Название', { exact: true }).fill(`Книга ${code}`)
  await page.getByLabel('Описание', { exact: true }).fill('Описание книги')
  await page.getByLabel('Цена', { exact: true }).fill('1500')
  await page.getByLabel('Теги через запятую').fill('книги, тест')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('heading', { name: `Книга ${code}`, exact: true })).toBeVisible()
}

